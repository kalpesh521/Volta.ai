def test_load_profile_by_hour_of_day():
    hist = synth_history(with_solar=False)
    model = build_load_model(hist, now=NOW, tz=IST)
    assert model.method == "profile" and model.days >= 5
    for hour in (2, 9, 18):
        est = model.predict(datetime(2026, 11, 15, hour, tzinfo=IST), 6.0)
        expected = 0.5 + 0.5 * math.sin(math.pi * hour / 12)
        assert est.p50_kw == pytest.approx(expected, abs=0.1)
        assert est.p10_kw <= est.p50_kw <= est.p90_kw


def test_load_ewma_prefers_recent_days():
    def load_for(local):  # older days 1.0 kW, last two days 3.0 kW
        return 3.0 if (NOW.astimezone(IST) - local).days < 2 else 1.0

    model = build_load_model(synth_history(with_solar=False, load_for=load_for), now=NOW, tz=IST)
    assert model.predict(datetime(2026, 11, 15, 10, tzinfo=IST), 0).p50_kw > 1.8  # plain mean would be ~1.67


def test_weekday_weekend_split_only_with_enough_data():
    def load_for(local):
        return 2.0 if local.weekday() in (5, 6) else 1.0

    rich = build_load_model(synth_history(days=14, with_solar=False, load_for=load_for), now=NOW, tz=IST)
    assert rich.uses_daytype_split
    sat = rich.predict(datetime(2026, 11, 21, 10, tzinfo=IST), 0).p50_kw  # Saturday
    wed = rich.predict(datetime(2026, 11, 18, 10, tzinfo=IST), 0).p50_kw
    assert sat == pytest.approx(2.0, abs=0.1) and wed == pytest.approx(1.0, abs=0.1)

    thin = build_load_model(synth_history(days=6, with_solar=False, load_for=load_for), now=NOW, tz=IST)
    assert not thin.uses_daytype_split  # <3 weekend days: one blended profile


def test_load_falls_back_to_flat_then_unknown():
    recent = [HistoryPoint(NOW - timedelta(minutes=m), None, 1.2) for m in (50, 30, 10)]
    flat = build_load_model(recent, now=NOW, tz=IST)
    assert flat.method == "flat"
    est = flat.predict(NOW.astimezone(IST), 2)
    assert est.p50_kw == pytest.approx(1.2) and est.p10_kw < 1.2 < est.p90_kw

    stale = [HistoryPoint(NOW - timedelta(hours=9), None, 1.2)]
    assert build_load_model(stale, now=NOW, tz=IST).method == "unknown"
    assert build_load_model([HistoryPoint(NOW, 1.0, None)], now=NOW, tz=IST).method == "unknown"
    assert build_load_model([], now=NOW, tz=IST).predict(NOW, 1) is None


def test_load_interval_widens_with_lead_time():
    model = build_load_model(synth_history(with_solar=False), now=NOW, tz=IST)
    t = datetime(2026, 11, 15, 10, tzinfo=IST)
    near, far = model.predict(t, 1), model.predict(t, 40)
    assert (far.p90_kw - far.p10_kw) > (near.p90_kw - near.p10_kw)


