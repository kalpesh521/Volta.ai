async def test_facts_surplus_window_and_evening_deficit():
    r = await forecast(inputs(history=synth_history(), horizon_hours=30), ConstWeather(10), NOW)
    facts = r.to_facts()
    window = facts["surplus_window"]
    assert window is not None
    start = datetime.fromisoformat(window["start"])
    end = datetime.fromisoformat(window["end"])
    assert end > start and 9 <= start.hour <= 13 and 12 <= end.hour <= 18
    inside = [s for s in r.slots[:24] if start <= s.start < end]
    assert all(s.net_kw_p50 > 0.1 for s in inside)
    assert window["surplus_kwh"] == pytest.approx(sum(s.net_kw_p50 for s in inside), abs=0.06)
    ev = facts["evening_deficit"]
    assert ev["window"].startswith("18:00") and ev["hours_covered"] == 5
    expected = sum(max(0.0, s.load_kw_p50 - s.solar_kw_p50) for s in r.slots if s.start.date().isoformat() == ev["date"] and 18 <= s.start.hour <= 22)
    assert ev["deficit_kwh"] == pytest.approx(expected, abs=0.06)


def test_evening_deficit_never_counts_surplus_hours_as_negative_deficit():
    from app.agents_platform.agents.forecast.facts import _evening_deficit
    from app.agents_platform.agents.forecast.result import ForecastSlot

    def slot(hour: int, solar: float, load: float) -> ForecastSlot:
        return ForecastSlot(
            start=datetime(2026, 6, 21, hour, tzinfo=IST), lead_hours=1, cloud_cover_pct=0,
            solar_kw_p10=solar, solar_kw_p50=solar, solar_kw_p90=solar,
            load_kw_p10=load, load_kw_p50=load, load_kw_p90=load,
        )

    ev = _evening_deficit([slot(18, solar=3.0, load=1.0), slot(19, solar=0.0, load=2.0), slot(20, solar=0.0, load=1.5)])
    assert ev["deficit_kwh"] == pytest.approx(3.5)  # the 18:00 surplus does not offset the later deficit
    assert ev["hours_covered"] == 3
    assert _evening_deficit([slot(12, 3.0, 1.0)]) is None


