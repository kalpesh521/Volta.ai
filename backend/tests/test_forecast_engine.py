IST = ZoneInfo("Asia/Kolkata")
LAT, LON = 18.52, 73.86  # Pune
NOW = datetime(2026, 11, 14, 4, 0, tzinfo=timezone.utc)  # 09:30 IST, Saturday
ARRAY = ArrayParams(LAT, LON, capacity_kwp=5.0, inverter_kw=5.0)


def inputs(**kw: object) -> ForecastInputs:
    base: dict[str, object] = dict(
        latitude=LAT, longitude=LON, timezone="Asia/Kolkata", solar_capacity_kwp=5.0, inverter_capacity_kw=5.0
    )
    base.update(kw)
    return ForecastInputs(**base)  # type: ignore[arg-type]


class ConstWeather:
    """Stub port: constant cloud cover."""

    def __init__(self, cloud: float, kind: str = "model", precip: float | None = None, temp: float | None = None):
        self.cloud, self.kind, self.precip, self.temp = cloud, kind, precip, temp

    async def hourly(self, *, latitude: float, longitude: float, times: Sequence[datetime]) -> WeatherSeries:
        hours = tuple(WeatherHour(t, self.cloud, self.precip, self.temp) for t in times)
        return WeatherSeries("stub", self.kind, hours)  # type: ignore[arg-type]


class FailingWeather:
    def __init__(self, exc: Exception | None = None):
        self.exc = exc or ForecastWeatherError("boom")

    async def hourly(self, *, latitude: float, longitude: float, times: Sequence[datetime]) -> WeatherSeries:
        raise self.exc


def synth_history(
    *,
    days: int = 6,
    pr_scale: float = 0.9,
    cloud_for_day=lambda d: 0.0,
    load_for=lambda local: 0.5 + 0.5 * math.sin(math.pi * local.hour / 12),
    step_minutes: int = 15,
    end: datetime = NOW,
    with_solar: bool = True,
    with_load: bool = True,
) -> list[HistoryPoint]:
    """Telemetry generated by the engine's own physics (so the right calibration factor is known)."""
    arr = ArrayParams(LAT, LON, 5.0, 5.0, performance_ratio=ARRAY.performance_ratio * pr_scale)
    out: list[HistoryPoint] = []
    t = end - timedelta(days=days)
    while t < end:
        local = t.astimezone(IST)
        d = (end - t).days
        solar = physics_power_kw(t, arr, cloud_cover_percent=cloud_for_day(d)) if with_solar else None
        load = load_for(local) if with_load else None
        out.append(HistoryPoint(t, solar, load))
        t += timedelta(minutes=step_minutes)
    return out


