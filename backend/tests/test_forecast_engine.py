def test_power_is_non_increasing_with_cloud_cover():
    for hour_utc in (3, 4, 5, 6, 7, 8, 9, 10, 11):
        t = datetime(2026, 11, 14, hour_utc, 15, tzinfo=timezone.utc)
        series = [physics_power_kw(t, ARRAY, cloud_cover_percent=c) for c in range(0, 101, 10)]
        assert all(a >= b - 1e-9 for a, b in zip(series, series[1:])), (hour_utc, series)
    t = datetime(2026, 11, 14, 7, 0, tzinfo=timezone.utc)
    assert physics_power_kw(t, ARRAY, cloud_cover_percent=100) < 0.5 * physics_power_kw(t, ARRAY, cloud_cover_percent=0)


