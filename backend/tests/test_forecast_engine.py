def _open_meteo_payload(start: datetime, hours: int = 96, cloud=lambda i: 10.0 + i) -> dict:
    stamps = [(start + timedelta(hours=i)).strftime("%Y-%m-%dT%H:%M") for i in range(hours)]
    return {
        "hourly": {
            "time": stamps,
            "cloud_cover": [cloud(i) for i in range(hours)],
            "temperature_2m": [25.0 + i * 0.1 for i in range(hours)],
            "precipitation": [0.0] * hours,
        }
    }


def _client(handler) -> httpx.AsyncClient:
    return httpx.AsyncClient(transport=httpx.MockTransport(handler))


async def test_open_meteo_parses_and_interpolates_half_hour_offsets():
    seen: list[httpx.Request] = []

    def handler(request: httpx.Request) -> httpx.Response:
        seen.append(request)
        return httpx.Response(200, json=_open_meteo_payload(datetime(2026, 11, 14, tzinfo=timezone.utc)))

    w = OpenMeteoWeather(client=_client(handler))
    # IST hour start 10:00 IST == 04:30 UTC: halfway between the 04:00 (cloud 14) and 05:00 (cloud 15) marks.
    t = datetime(2026, 11, 14, 10, 0, tzinfo=IST)
    series = await w.hourly(latitude=LAT, longitude=LON, times=[t, t + timedelta(minutes=30)])
    assert series.kind == "model" and series.source == "open-meteo"
    assert series.hours[0].cloud_cover_pct == pytest.approx(14.5)
    assert series.hours[1].cloud_cover_pct == pytest.approx(15.0)
    assert series.hours[0].temperature_c == pytest.approx(25.45)
    params = seen[0].url.params
    assert params["hourly"] == "cloud_cover,temperature_2m,precipitation"
    assert params["timezone"] == "UTC" and seen[0].url.host == "api.open-meteo.com"


async def test_open_meteo_cache_hits_expires_and_rounds_key():
    calls = 0
    now = [0.0]

    def handler(request: httpx.Request) -> httpx.Response:
        nonlocal calls
        calls += 1
        return httpx.Response(200, json=_open_meteo_payload(datetime(2026, 11, 14, tzinfo=timezone.utc)))

    w = OpenMeteoWeather(client=_client(handler), ttl_seconds=100, clock=lambda: now[0])
    t = [datetime(2026, 11, 14, 10, 0, tzinfo=timezone.utc)]
    await w.hourly(latitude=18.521, longitude=73.861, times=t)
    await w.hourly(latitude=18.524, longitude=73.864, times=t)  # same rounded cell
    assert calls == 1
    now[0] = 101.0
    await w.hourly(latitude=18.521, longitude=73.861, times=t)
    assert calls == 2
    await w.hourly(latitude=19.9, longitude=73.861, times=t)  # different cell
    assert calls == 3


