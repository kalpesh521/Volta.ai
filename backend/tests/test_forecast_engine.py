def test_sunrise_hour_is_partial_not_all_or_nothing():
    sunrise_slot = datetime(2026, 11, 14, 1, 0, tzinfo=timezone.utc)  # 06:30-07:30 IST, sun up ~06:50
    first_half = physics_power_kw(sunrise_slot + timedelta(minutes=10), ARRAY)
    second_half = physics_power_kw(sunrise_slot + timedelta(minutes=50), ARRAY)
    avg = slot_power_kw(sunrise_slot, ARRAY, cloud_cover_percent=0)
    assert first_half == 0.0 < second_half  # the sun comes up inside the slot
    assert 0.0 < avg < second_half


