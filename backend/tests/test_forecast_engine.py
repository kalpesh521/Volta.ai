async def test_calibrated_forecast_tracks_a_real_array_better_than_default():
    hist = synth_history(pr_scale=0.9, with_load=False)
    truth = ArrayParams(LAT, LON, 5.0, 5.0, performance_ratio=ARRAY.performance_ratio * 0.9)
    cal = await forecast(inputs(history=hist), ConstWeather(0), NOW)
    default = await forecast(inputs(), ConstWeather(0), NOW)

    def err(r) -> float:
        return sum(abs(s.solar_kw_p50 - slot_power_kw(s.start, truth, cloud_cover_percent=0)) for s in r.slots)

