def test_never_above_inverter_and_clipping_flattens_peak():
    big = ArrayParams(LAT, LON, capacity_kwp=12.0, inverter_kw=5.0)
    vals = [
        slot_power_kw(datetime(2026, 11, 14, h, 0, tzinfo=timezone.utc), big, cloud_cover_percent=0) for h in range(0, 24)
    ]
    assert max(vals) <= 5.0 + 1e-9
    assert sum(1 for v in vals if abs(v - 5.0) < 1e-6) >= 2  # a flat clipped top, not one lucky hour
    unclipped = physics_power_kw(datetime(2026, 11, 14, 7, 0, tzinfo=timezone.utc), big, clip=False)
    assert unclipped > 5.0


