def test_hot_ambient_lowers_output_and_performance_ratio_scales_it():
    t = datetime(2026, 11, 14, 7, 0, tzinfo=timezone.utc)
    assert physics_power_kw(t, ARRAY, ambient_c=45) < physics_power_kw(t, ARRAY, ambient_c=15)
